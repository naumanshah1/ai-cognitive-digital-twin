"""Google Gemini LLM provider implementation using langchain-google-genai."""

import json
import re
from typing import Any, Dict, List, Optional
from langchain_core.messages import HumanMessage, SystemMessage
from langchain_google_genai import ChatGoogleGenerativeAI

from app.agent.models import AgentPlan, AgentRequest, ToolCallProposal, ToolExecutionResult
from app.agent.providers import BaseLLMProvider
from app.core.config import get_settings


class GeminiProvider(BaseLLMProvider):
    """Integrates Google Gemini via LangChain for autonomous planning and synthesis."""

    def __init__(
        self,
        model_id: Optional[str] = None,
        api_key: Optional[str] = None,
        temperature: float = 0.1,
    ):
        settings = get_settings()
        self.model_id = model_id or settings.llm_model
        if api_key is not None:
            resolved_key = api_key
        else:
            resolved_key = settings.effective_gemini_api_key

        if not resolved_key:
            raise ValueError(
                "Gemini API key is not configured. Set GEMINI_API_KEY in .env or provide it securely."
            )

        self._llm = ChatGoogleGenerativeAI(
            model=self.model_id,
            google_api_key=resolved_key,
            temperature=temperature,
        )

    def generate_plan(
        self,
        request: AgentRequest,
        available_tools: List[Dict[str, Any]],
        iteration: int = 0,
        prior_results: Optional[List[ToolExecutionResult]] = None,
    ) -> AgentPlan:
        """Prompt Gemini to analyze the request and propose approved tool calls."""
        tools_str = json.dumps(available_tools, indent=2)

        prior_results_str = ""
        if prior_results:
            prior_results_str = "\nPrior Tool Execution Results:\n" + "\n".join(
                f"- {r.tool_name} ({r.status.value}): {r.evidence_summary}"
                for r in prior_results
            )

        system_prompt = (
            "You are the Cognitive Digital Twin Autonomous Planning Engine.\n"
            "Analyze the user's natural language request and select ONLY appropriate tools from the allowlist.\n"
            "Rules:\n"
            "1. You must output VALID JSON only with this schema:\n"
            "   {\n"
            "     \"intent\": \"<intent_category>\",\n"
            "     \"rationale\": \"<why these tools were chosen>\",\n"
            "     \"planned_tools\": [\n"
            "       {\"tool_name\": \"<name>\", \"arguments\": {<args>}, \"reason\": \"<why>\", \"expected_output\": \"<output>\"}\n"
            "     ],\n"
            "     \"requires_clarification\": false,\n"
            "     \"clarification_message\": null\n"
            "   }\n"
            "2. Never diagnose clinical illness (no burnout, depression, or psychiatric claims).\n"
            "3. If prior tools already answered the request, return empty planned_tools.\n"
            "4. Do NOT hallucinate tool names. Choose ONLY from the registered tools.\n"
            f"Available Tools:\n{tools_str}"
        )

        user_content = (
            f"User Query: {request.query}\n"
            f"Target User ID: {request.user_id or 'synthetic_0001'}\n"
            f"Explicit Parameters: {request.simulation_params or {}}\n"
            f"{prior_results_str}"
        )

        try:
            response = self._llm.invoke([
                SystemMessage(content=system_prompt),
                HumanMessage(content=user_content),
            ])
            content = str(response.content)
            parsed = self._extract_json(content)

            planned = [
                ToolCallProposal(
                    tool_name=t["tool_name"],
                    arguments=t.get("arguments", {}),
                    reason=t.get("reason", "Selected by Gemini planner"),
                    expected_output=t.get("expected_output", "Structured telemetry evidence"),
                )
                for t in parsed.get("planned_tools", [])
            ]

            return AgentPlan(
                intent=parsed.get("intent", "general_query"),
                rationale=parsed.get("rationale", "Plan generated by Gemini LLM"),
                planned_tools=planned,
                requires_clarification=parsed.get("requires_clarification", False),
                clarification_message=parsed.get("clarification_message"),
            )
        except Exception as ex:
            err_msg = str(ex)
            # Provide clear diagnostics for known model/API issues without exposing secrets
            if "not found" in err_msg.lower() or "404" in err_msg:
                raise RuntimeError(
                    f"Gemini model '{self.model_id}' was not found or is unavailable on this account. "
                    "Official supported models include 'gemini-2.0-flash' or 'gemini-1.5-flash'. "
                    f"Underlying error: {err_msg}"
                ) from ex
            elif "quota" in err_msg.lower() or "429" in err_msg:
                raise RuntimeError(
                    f"Gemini API quota exceeded or rate limit reached for model '{self.model_id}'."
                ) from ex
            elif "api_key" in err_msg.lower() or "authentication" in err_msg.lower() or "403" in err_msg:
                raise RuntimeError("Gemini API authentication failed. Verify API key validity.") from ex
            raise RuntimeError(f"Gemini planning failed: {err_msg}") from ex

    def synthesize_findings(
        self,
        request: AgentRequest,
        tool_results: List[ToolExecutionResult],
    ) -> Dict[str, Any]:
        """Prompt Gemini to synthesize verified findings and an executive summary from evidence."""
        evidence_lines = [
            f"Tool: {r.tool_name} | Status: {r.status.value}\nEvidence: {r.evidence_summary}\n"
            for r in tool_results
        ]
        evidence_text = "\n".join(evidence_lines)

        system_prompt = (
            "You are the Cognitive Digital Twin Behavioral Intelligence Synthesizer.\n"
            "Synthesize an evidence-grounded response strictly adhering to the executed tool outputs.\n"
            "Rules:\n"
            "1. Output valid JSON only with keys 'summary' (str) and 'findings' (list of str).\n"
            "2. Ground every single claim in the provided tool outputs. Do not invent metrics.\n"
            "3. State that all observations stem from synthetic telemetry and predictive models.\n"
            "4. NEVER assert clinical diagnoses (no burnout, depression, or anxiety).\n"
            "5. NEVER claim that simulated score changes are proven causal guarantees."
        )

        user_content = (
            f"User Query: {request.query}\n"
            f"Target User: {request.user_id}\n\n"
            f"Executed Tool Evidence:\n{evidence_text}"
        )

        try:
            response = self._llm.invoke([
                SystemMessage(content=system_prompt),
                HumanMessage(content=user_content),
            ])
            parsed = self._extract_json(str(response.content))
            return {
                "summary": parsed.get("summary", "Analysis completed based on recorded telemetry."),
                "findings": parsed.get("findings", [r.evidence_summary for r in tool_results]),
            }
        except Exception as ex:
            # Deterministic fallback synthesis on LLM error
            return {
                "summary": f"Telemetry synthesis generated from {len(tool_results)} executed tool(s).",
                "findings": [r.evidence_summary for r in tool_results if r.evidence_summary],
            }

    @staticmethod
    def _extract_json(text: str) -> Dict[str, Any]:
        """Safely extract JSON object from markdown-wrapped LLM text."""
        # Try direct parse
        text_clean = text.strip()
        try:
            return json.loads(text_clean)
        except json.JSONDecodeError:
            pass

        # Match ```json ... ``` blocks
        match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text_clean, re.DOTALL)
        if match:
            try:
                return json.loads(match.group(1))
            except json.JSONDecodeError:
                pass

        # Fallback: search for first { to last }
        start = text_clean.find("{")
        end = text_clean.rfind("}")
        if start != -1 and end != -1 and end > start:
            try:
                return json.loads(text_clean[start : end + 1])
            except json.JSONDecodeError:
                pass

        raise ValueError(f"Failed to extract valid JSON from LLM response: {text[:200]}...")
